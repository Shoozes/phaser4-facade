#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, "examples", "phaser4-facade-grout13-canvas-stack-clipped.html");
const OUTPUT = path.join(ROOT, "examples", "grout-vault-all-in-one.html");
const ATLAS_PATH = path.join(ROOT, "examples", "fruit-shot", "canvas-stack-payload.js");
const FONT_PATH = path.join(ROOT, "examples", "fruit-shot", "font-payload.js");

const atlas = await import(pathToFileURL(ATLAS_PATH).href);
const font = await import(pathToFileURL(FONT_PATH).href);
let html = fs.readFileSync(SOURCE, "utf8").replace(/\r\n?/g, "\n");

html = html
    .replace(/^import \{ PIXEL_FONT_PAYLOAD, PIXEL_FONT_GLYPHS, PIXEL_FONT_METRICS \} from "fruit-shot\/font-payload";\n/m, "")
    .replace(/^import \{ CANVAS_STACK_ATLAS_PAYLOAD \} from "fruit-shot\/atlas-payload";\n/m, "")
    .replace(/^\s+"fruit-shot\/font-payload": "[^"]+",\n/m, "")
    .replace(/^\s+"fruit-shot\/atlas-payload": "[^"]+"\n/m, "")
    .replace(/,\n(\s*}\n}\n<\/script>)/, "\n$1");

const generatedBlock = `/* GENERATED_DATA_BEGIN */
const CANVAS_STACK_ATLAS_PAYLOAD = Object.freeze(${JSON.stringify(atlas.CANVAS_STACK_ATLAS_PAYLOAD)});
const PIXEL_FONT_PAYLOAD = ${JSON.stringify(font.PIXEL_FONT_PAYLOAD)};
const PIXEL_FONT_GLYPHS = ${JSON.stringify(font.PIXEL_FONT_GLYPHS)};
const PIXEL_FONT_METRICS = ${JSON.stringify(font.PIXEL_FONT_METRICS)};
/* GENERATED_DATA_END */`;
html = html
    .replace('architecture:"single-canvas-stacked-planes"', 'architecture:"grout-vault-all-in-one"')
    .replace("installGrout13Bridge(GM, GROUT13);", `${generatedBlock}\n\ninstallGrout13Bridge(GM, GROUT13);`);
html = `<!-- Generated by scripts/generate-grout-vault.mjs. Edit the source canvas-stack example and regenerate. -->\n${html}`;

fs.writeFileSync(OUTPUT, html, "utf8");
console.log(`[ok] Generated ${path.relative(ROOT, OUTPUT).replaceAll("\\", "/")} with embedded Grout13 atlas and font payloads.`);
